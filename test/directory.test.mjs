import { join } from 'node:path';
import { tmpdir } from 'node:os';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { startDaemon } from '../src/daemon.mjs';
import { directory, formatDirectory } from '../src/directory.mjs';

test('directory lists only current-channel peers, marks self, and distinguishes queued mail from blocked sending', async t => {
  const home = mkdtempSync(join(tmpdir(), 'relay-directory-'));
  let resolved = [], nativeTitle = 'Actual chat title', lookupFails = false;
  const daemon = await startDaemon({ home, port: 0, adapters: {}, interval: 60000,
    resolveTitles: async identities => {
      resolved = identities;
      if (lookupFails) throw new Error('Native metadata unavailable');
      return new Map(identities.map(identity => [identity.id, { title: nativeTitle, title_source: 'test-native-metadata' }]));
    } });
  t.after(async () => { await daemon.close(); rmSync(home, { recursive: true, force: true }); });
  const current = daemon.store.register({ alias: 'core', kind: 'codex', native_id: randomUUID(), channel: 'main' });
  const claude = daemon.store.register({ alias: 'website', kind: 'claude-desktop', native_id: randomUUID(), channel: 'main' });
  const agy = daemon.store.register({ alias: 'research', kind: 'agy', native_id: randomUUID(), channel: 'main' });
  const unrelated = daemon.store.register({ alias: 'private-project', kind: 'manual', channel: 'elsewhere' });
  daemon.store.pause(claude.id, true);
  const profile = { ...current, url: daemon.url };
  const result = await directory(profile);
  assert.equal(result.channel, 'main');
  assert.equal(result.current_session.id, current.id);
  assert.equal(result.current_session.title, nativeTitle);
  assert.equal(result.sessions.find(row => row.id === claude.id).title, nativeTitle);
  assert.equal(resolved.length, 3, 'native titles are resolved only for visible channel members');
  assert.ok(!resolved.some(row => row.id === unrelated.id));
  assert.ok(resolved.every(row => !('token' in row)));
  assert.equal(result.sessions.length, 3);
  assert.equal(result.sessions[0].id, current.id);
  assert.equal(result.sessions[0].can_send, false);
  assert.equal(result.sessions.find(row => row.id === claude.id).paused, true);
  assert.equal(result.sessions.find(row => row.id === claude.id).can_send, true, 'paused recipients still accept queued mail');
  assert.equal(result.sessions.find(row => row.id === agy.id).agent, 'Antigravity App');
  assert.ok(!result.sessions.some(row => row.id === unrelated.id));
  assert.ok(result.sessions.every(row => !('token' in row) && !('native_id' in row)));
  assert.match(formatDirectory(result), /core \(you\)/);
  assert.match(formatDirectory(result), /Paused; messages queue/);
  assert.match(formatDirectory(result), /Actual chat title/);
  nativeTitle = 'Renamed\nChat\u001b[31m';
  const renamed = await directory(profile);
  assert.equal(renamed.sessions[0].title, nativeTitle, 'JSON preserves the exact title');
  assert.ok(!formatDirectory(renamed).includes('\u001b'), 'table must not emit terminal control sequences');
  assert.ok(formatDirectory(renamed).includes('Renamed\\u000aChat\\u001b[31m'));
  lookupFails = true;
  const unavailable = await directory(profile);
  assert.equal(unavailable.sessions[0].title, null);
  assert.match(formatDirectory(unavailable), /Title unavailable/);
  daemon.store.pause(current.id, true);
  const paused = await directory(profile);
  assert.ok(paused.sessions.every(row => !row.can_send));
  assert.match(formatDirectory(paused), /new sends are blocked/);
  assert.equal(daemon.store.history('main').length, 0, 'directory lookup sends no notifications');
  const alone = await directory({ ...unrelated, url: daemon.url });
  assert.match(formatDirectory(alone), /No other sessions are registered/);
});
